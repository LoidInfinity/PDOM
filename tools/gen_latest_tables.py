"""Generate the C# table file for the UserChoiceLatest hash from the reference .inc."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "tools" / "ref" / "tables.inc"
OUT = ROOT / "src" / "Keep.Core" / "Associations" / "UserChoiceLatestTables.cs"

NAMES = {
    "kTokenRegionHex": "TokenRegion",
    "kLongRewindTableHex": "LongRewind",
    "kFallbackTokenCodeTableHex": "FallbackTokenCode",
    "kByteClassTableHex": "ByteClass",
    "kTokenBitWidthTableHex": "TokenBitWidth",
    "kShortRewindTableHex": "ShortRewind",
}


def extract(text, cpp_name):
    m = re.search(cpp_name + r"\s*=\s*((?:\s*\"[0-9a-fA-F]*\"\s*)+);", text)
    if not m:
        raise SystemExit("missing " + cpp_name)
    return "".join(re.findall(r'"([0-9a-fA-F]*)"', m.group(1)))


def chunk(hexstr, size=512):
    parts = [hexstr[i:i + size] for i in range(0, len(hexstr), size)]
    return "\n        + ".join(f'"{p}"' for p in parts)


def main():
    text = SRC.read_text(encoding="utf-8", errors="ignore")
    lines = [
        "// <auto-generated>",
        "// Lookup tables for the Windows 11 24H2+ UserChoiceLatest hash.",
        "// Derived from the MIT-licensed cssxn/UserChoiceLatestHash reference",
        "// implementation (UserChoiceLatestHashTables.inc). Do not hand-edit.",
        "// </auto-generated>",
        "",
        "namespace Keep.Core.Associations;",
        "",
        "internal static class UserChoiceLatestTables",
        "{",
    ]
    for cpp, cs in NAMES.items():
        hexstr = extract(text, cpp)
        lines.append(f"    public const string {cs}Hex =")
        lines.append("        " + chunk(hexstr) + ";")
        lines.append("")
    lines.append("    public static byte[] Decode(string hex) => Convert.FromHexString(hex);")
    lines.append("}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT, OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()

